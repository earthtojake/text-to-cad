"""Master package spec + design language for the F1 concept car.

THIS FILE IS THE CONTRACT. Every part module reads its dimensions and its
surface vocabulary from here. Do not hard-code a number in a part module that
belongs in this file, and do not edit this file from a part module's task —
changing a shared datum silently moves somebody else's part.

--------------------------------------------------------------------------
COORDINATE SYSTEM
--------------------------------------------------------------------------
Units: millimetres. Right-handed.

    +X  forward   (toward the nose)
    +Y  left      (driver's left)
    +Z  up

    ORIGIN = ground plane, car centreline, FRONT AXLE.

So the front axle is x = 0, the rear axle is x = -3600, the ground is z = 0,
and the car is mirror-symmetric about the y = 0 plane. Every part module
builds in these car coordinates directly (no part-local frames) so the
assembly is a flat list of correctly-placed children and the animation sidecar
can rotate things about real, stated pivots.

--------------------------------------------------------------------------
DESIGN LANGUAGE  (the aesthetic rubric, expressed as rules)
--------------------------------------------------------------------------
The car is one idea repeated at five scales. Obey these or the car stops
reading as a single object:

1.  ONE SECTION FAMILY. Every aerodynamic element — front wing elements, beam
    wing, rear wing, floor fences, brake-duct vanes, diveplanes — is a lofted
    airfoil from `lib.airfoil_face()`. Nothing aerodynamic is a swept
    rectangle. Trailing edges close to `TE_THICKNESS` (1.2 mm) and never more.

2.  ONE BLADE SECTION. Every structural member in the airstream — wishbones,
    pushrods, track rods, wing pillars, mirror stalks, the rear wing pylon —
    is a lofted teardrop from `lib.blade_face()`, tapering along its length,
    with its long axis aligned to local flow (i.e. to X). Nothing structural
    is a plain cylinder where it can be seen.

3.  ONE TIP TREATMENT. Wherever an aero element ends outboard, it rolls over
    with radius `TIP_ROLL_R` into the surface it meets. Wing tips, endplate
    top edges, floor edges, diffuser side exits all share that radius family.

4.  ONE FEATURE-LINE RULE. A feature line either runs into another line, dies
    into a panel break, or wraps around an edge. It never fades out in the
    middle of a surface. The `SHOULDER_LINE` below is the car's primary
    feature line and every module that touches it must hand it off.

5.  RHYTHM. Multi-element cascades use the geometric progressions defined
    below (`CHORD_RATIO`, `GAP_RATIO`) — chord shrinks, gap tightens, and
    incidence steps up by a smoothly growing delta. Never arbitrary.

6.  RESTRAINT. Three material families only: carbon (near-black, most of the
    car), exposed metal (titanium / anodized / heat-tinted), and ONE accent —
    `ACCENT` vermillion — used as a thin edge stripe, a machined ring, or a
    single small jewel-like body. If in doubt, use less accent.

7.  DELICACY. Suspension and linkage members read as highly stressed and thin.
    Nothing in the airstream is chunky. Root-to-tip taper is mandatory.
"""

