# DERIVED CASCADE HELPERS
# ==========================================================================


def cascade_chords(root_chord: float, n: int, ratio: float = CHORD_RATIO):
    """Geometric chord progression for an n-element cascade."""
    return [root_chord * ratio**i for i in range(n)]


def cascade_gaps(root_gap: float, n: int, ratio: float = GAP_RATIO):
    """Geometric slot-gap progression between n elements (n-1 gaps)."""
    return [root_gap * ratio**i for i in range(max(n - 1, 0))]


def lerp(a: float, b: float, t: float) -> float:
    return a + (b - a) * t


def smoothstep(t: float) -> float:
    t = min(max(t, 0.0), 1.0)
    return t * t * (3.0 - 2.0 * t)


def shoulder_at(x: float):
    """Sample the primary feature line at station x -> (y, z).

    Modules that carry the shoulder line call this so the crease is continuous
    across panel breaks instead of each module inventing its own path.
    """
    pts = SHOULDER_LINE
    if x >= pts[0][0]:
        return pts[0][1], pts[0][2]
    if x <= pts[-1][0]:
        return pts[-1][1], pts[-1][2]
    for i in range(len(pts) - 1):
        x0, y0, z0 = pts[i]
        x1, y1, z1 = pts[i + 1]
        if x1 <= x <= x0:
            t = smoothstep((x0 - x) / (x0 - x1))
            return lerp(y0, y1, t), lerp(z0, z1, t)
    return pts[-1][1], pts[-1][2]


def deg(a: float) -> float:
    return a * math.pi / 180.0
