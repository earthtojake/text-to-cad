# ==========================================================================
# MATERIAL PALETTE — RED bodywork over carbon, exposed metal, ONE accent
#
# The car is red. It is NOT red everywhere, and that is deliberate: on a real
# red car the painted skin is red while the aerodynamic and structural carbon
# stays black, and the contrast between the two is most of why it looks
# expensive. So the split is:
#
#   CARBON_GLOSS  the painted OUTER SKIN -> RED. Nose, survival cell, sidepod
#                 panels, engine cover, airbox, floor top, wheel covers.
#   CARBON        structural + aero elements -> stays near-black. Wing
#                 elements, endplates, halo shroud, internals. Black wings
#                 against a red body is the classic read.
#   CARBON_MATTE  underfloor, inner ducts, tunnel roofs -> stays near-black.
#   CARBON_WEAVE  exposed twill flanges and the plank -> stays dark, warmed a
#                 touch so it sits between the red and the black.
#
# Value discipline still applies: the red is DEEP, not signal-bright. The
# stage runs saturation 1.10 and contrast 1.28, so a pure 0.8-red blows out to
# orange in the key and loses every crease. Keeping the base dark lets the
# highlight do the work and keeps the shoulder line readable.
# ==========================================================================

