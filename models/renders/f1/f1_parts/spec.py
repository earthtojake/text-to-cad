# ==========================================================================
# DRS MECHANISM — a visible four-bar, not a hidden box
#
# The flap rotates about DRS_PIVOT (an axis along Y). A machined bellcrank on
# the inner face of each endplate swings about DRS_CRANK_PIVOT and drives a
# polished link to a lug on the flap's underside. The link length is DERIVED
# from the closed pose so the four-bar closes exactly at every DRS value.
# ==========================================================================

DRS_PIVOT = (RW_DRS_PIVOT_X, 0.0, RW_DRS_PIVOT_Z)
DRS_CRANK_PIVOT = (-3894.0, 462.0, 800.0)
DRS_CRANK_R = 66.0
DRS_CRANK_ANGLE_CLOSED_DEG = 118.0  # crank arm direction when DRS is shut
DRS_LUG_R = 88.0  # flap lug radius from the flap pivot
DRS_LUG_ANGLE_CLOSED_DEG = 214.0  # lug direction from the pivot when shut
DRS_LINK_Y = 462.0  # the linkage plane, just inboard of the endplate


def _drs_point(center, radius: float, angle_deg: float):
    a = math.radians(angle_deg)
    return (
        center[0] + radius * math.cos(a),
        DRS_LINK_Y,
        center[2] + radius * math.sin(a),
    )


DRS_CRANK_END_CLOSED = _drs_point(
    DRS_CRANK_PIVOT, DRS_CRANK_R, DRS_CRANK_ANGLE_CLOSED_DEG
)
DRS_LUG_CLOSED = _drs_point(DRS_PIVOT, DRS_LUG_R, DRS_LUG_ANGLE_CLOSED_DEG)
DRS_LINK_L = math.dist(DRS_CRANK_END_CLOSED, DRS_LUG_CLOSED)

