# The flat tunnel between the nacelles.  Its deck sits a little BELOW the
# nacelle crowns (a broad shallow valley, not a plateau) and its belly is
# essentially FLUSH with the nacelle undersides -- which is why the underside of
# a Tomcat reads as one wide flat plate with two shallow humps rather than as
# two tubes with a bridge between them.
# The forward entries BRIDGE THE SPLITTER GAP.  Between the fuselage side
# (0.820 m) and the inlet inner cowl (0.950 m) the real aircraft is OPEN -- the
# boundary-layer diverter slot -- so a section taken there is genuinely two
# disconnected regions and cannot be lofted as one closed wire.  The body is
# therefore lofted with the slot FILLED and the slot is cut afterwards, which
# also gives it crisp machined walls instead of a lofted approximation.
PANCAKE_TOP = [
    (6.290 * M, 0.300 * M), (7.400 * M, 0.380 * M),
    (8.400 * M, 0.450 * M), (9.500 * M, 0.500 * M), (11.000 * M, 0.530 * M),
    (13.500 * M, 0.545 * M), (15.500 * M, 0.545 * M), (16.150 * M, 0.535 * M),
    (17.200 * M, 0.510 * M), (18.360 * M, 0.455 * M),
]

PANCAKE_BOT = [
    (6.290 * M, -0.400 * M), (7.400 * M, -0.520 * M),
    (8.400 * M, -0.620 * M), (9.500 * M, -0.672 * M), (11.000 * M, -0.700 * M),
    (13.500 * M, -0.706 * M), (15.500 * M, -0.700 * M), (16.150 * M, -0.690 * M),
    (17.200 * M, -0.660 * M), (18.360 * M, -0.580 * M),
]


def forebody(x):
    """(half_width, top_z, bottom_z) of the forebody lobe, absolute heights
    relative to the waterline.  None where the forebody no longer exists."""
    if x < -1.0 or x > 16.150 * M:
        return None
    return (_curve(FOREBODY_HALF_W, x),
            _curve(FOREBODY_TOP, x),
            _curve(FOREBODY_BOT, x))


def nacelle(x):
    """(y_offset, r_lateral, r_vertical, axis_z) or None outside the run."""
    if x < X_INLET_LIP or x > LENGTH:
        return None
    return (_curve(NACELLE_Y, x), _curve(NACELLE_RY, x),
            _curve(NACELLE_RZ, x), _curve(NACELLE_Z, x))


def canopy_lobe(x):
    """(half_width, top_z) of the canopy/spine lobe, or None outside its run.

    The body is lofted THROUGH the canopy's own outer surface; the cockpit
    module cuts the opening out of it and builds the transparency from the same
    functions, so the glass sits exactly on the surface it came from.
    """
    if x < CANOPY_HALF_W[0][0] or x > CANOPY_HALF_W[-1][0]:
        return None
    return (_curve(CANOPY_HALF_W, x), _curve(CANOPY_TOP, x))


def pancake(x):
    """(top_z, bottom_z) of the flat tunnel, or None outside its run."""
    if x < X_INLET_LIP or x > X_BEAVER_TIP:
        return None
    return (_curve(PANCAKE_TOP, x), _curve(PANCAKE_BOT, x))


# ---------------------------------------------------------------------------
# glove -- the fixed leading-edge structure that flows forward into the
# forward fuselage.  Its LE is a straight 70.5 deg line; the TE follows the
# wing seal.
# ---------------------------------------------------------------------------

GLOVE_LE_TAN = math.tan(math.radians(GLOVE_LE_SWEEP))
X_GLOVE_AFT = 13.000 * M       # aft of here the glove has merged into the body


def glove_le_x(y):
    """Station of the glove leading edge at lateral offset y.

    ``X_GLOVE_LE_ROOT`` is the line's CENTRELINE INTERCEPT, which is a
    construction point inside the radome, not where the glove starts.  The glove
    physically begins at the inlet cowl -- see :func:`glove_outer_y`.
    """
    return X_GLOVE_LE_ROOT + abs(y) * GLOVE_LE_TAN


X_GLOVE_FADE0 = 12.100 * M     # glove outer edge starts blending to the nacelle
X_GLOVE_FADE1 = 13.400 * M     # ... and has fully merged by here


def glove_te_x(y):
    """Station where the glove has faded into the nacelle/pancake behind it."""
    t = clamp(abs(y) / Y_GLOVE_OUTER, 0.0, 1.0)
    return lerp(X_GLOVE_AFT + 0.900 * M, X_GLOVE_FADE1, t)


GLOVE_HALF_T = 0.155 * M       # glove slab half-thickness once past the LE
GLOVE_EDGE_R = 0.130 * M       # radius of the rounded outboard seal edge


def glove_half_thickness(x, y):
    """Half-thickness of the glove sheet.

    Sharp at the leading edge, then essentially CONSTANT going aft.  It must
    not taper back to zero: the glove's aft boundary is not a trailing edge, it
    is where the glove disappears into the nacelle, and a chordwise taper there
    leaves a zero-thickness sliver sticking out past the nacelle that no loft
    can survive.  Outboard it closes with a rounded edge -- the wing seal -- so
    the section shuts tangentially instead of on a knife edge.
    """
    le, te = glove_le_x(y), glove_te_x(y)
    if x <= le or x >= te:
        return 0.0
    t = clamp((x - le) / max(te - le, 1.0), 0.0, 1.0)
    ramp = min(t / 0.22, 1.0) ** 0.55
    h = GLOVE_HALF_T * ramp * (1.0 - 0.18 * t)
    edge0 = Y_GLOVE_OUTER - GLOVE_EDGE_R
    if abs(y) > edge0:
        u = clamp((abs(y) - edge0) / GLOVE_EDGE_R, 0.0, 1.0)
        h *= math.sqrt(max(0.0, 1.0 - u * u))
    return h


GLOVE_Z = 0.135 * M            # glove mid-surface at the root, above the axis


def glove_camber_z(x, y):
    """Mid-surface height of the glove above the waterline.

    The glove carries the aircraft's dihedral: it rises slightly outboard and
    lifts a little going aft, which is what makes the top view read as a
    continuous surface rather than a plate stuck on the side of a tube.
    """
    rise = 0.075 * M * (abs(y) / Y_GLOVE_OUTER) ** 1.6
    aft = 0.040 * M * smoothstep(X_GLOVE_LE_ROOT, X_PIVOT, x)
    return GLOVE_Z + rise + aft


def glove_outer_y(x):
    """Outboard extent of the fixed glove at station x (0 where absent).

    The glove does NOT start at the cockpit.  Forward of the inlet the Tomcat's
    plan silhouette is just the forebody: the drawing's outer edge holds at
    0.807 m through x = 5 m, where a cockpit-rooted glove would already have
    pushed it out past 1.0 m.  The glove leading edge picks up at the inlet
    cowl's outer wall (6.63 m, 1.706 m) and runs aft at a constant 69.2 deg --
    that straight line is the Tomcat's signature, and it is why the planform
    widens steadily from a third of the way back rather than tapering.
    """
    if x < X_INLET_LIP or x > X_GLOVE_FADE1:
        return 0.0
    y_le = (x - X_GLOVE_LE_ROOT) / GLOVE_LE_TAN     # leading-edge limited
    limit = Y_GLOVE_OUTER
    if x > X_GLOVE_FADE0:
        # Aft of the seal the glove edge does not just stop -- that would leave
        # a step in the plan silhouette.  It blends into the nacelle's own outer
        # line, so the two become one edge.
        na = nacelle(x)
        target = (na[0] + na[1]) if na else Y_GLOVE_OUTER
        limit = lerp(Y_GLOVE_OUTER, target,
                     smoothstep(X_GLOVE_FADE0, X_GLOVE_FADE1, x))
    return clamp(min(y_le, limit), 0.0, Y_GLOVE_OUTER)


# ---------------------------------------------------------------------------
# wing pivot geometry
# ---------------------------------------------------------------------------


def wing_tip_xy(sweep_deg=SWEEP, side=1):
    """Wingtip position (x, y) for a commanded LE sweep."""
    ang = math.radians(sweep_deg + WING_TIP_PHI)
    return (X_PIVOT + WING_PIVOT_R * math.sin(ang),
            side * (Y_PIVOT + WING_PIVOT_R * math.cos(ang)))


def wing_semi_span(sweep_deg=SWEEP):
    return abs(wing_tip_xy(sweep_deg)[1])


def wing_span(sweep_deg=SWEEP):
    return 2.0 * wing_semi_span(sweep_deg)


# ---------------------------------------------------------------------------
# convenience: waterline-relative -> world Z
# ---------------------------------------------------------------------------


def wz(z_rel, x=None):
    """World Z for a waterline-relative height, including the ground pitch."""
    z = WATERLINE + z_rel
    if x is not None and GROUND_PITCH:
        z += (x - X_MAIN_GEAR) * math.tan(math.radians(GROUND_PITCH))
    return z


def report():
    """Print the derived envelope so the numbers can be checked against spec."""
    lines = [
        f"length            {LENGTH/M:8.3f} m   (spec 19.110)",
        f"span @ {SWEEP:.0f} deg      {wing_span(SWEEP)/M:8.3f} m   (spec {SPAN_20/M:.3f})",
        f"span @ 68 deg     {wing_span(68)/M:8.3f} m   (spec {SPAN_68/M:.3f})",
        f"span @ 75 deg     {wing_span(75)/M:8.3f} m   (spec {SPAN_75/M:.3f})",
        f"stabilator span   {STAB_SPAN/M:8.3f} m",
        f"wheelbase         {WHEELBASE/M:8.3f} m",
        f"main track        {MAIN_TRACK/M:8.3f} m",
        f"inlet outer wall  {Y_INLET_OUTER/M:8.3f} m",
        f"wingtip @ {SWEEP:.0f} deg   x={wing_tip_xy(SWEEP)[0]/M:.3f} m  y={wing_tip_xy(SWEEP)[1]/M:.3f} m",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    print(report())
