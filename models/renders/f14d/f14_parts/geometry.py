"""F-14D Super Tomcat -- master geometry.

THE SINGLE SOURCE OF TRUTH.  Every part module imports this and QUERIES it.
Never hard-code a coordinate that this module can answer; if a part touches the
airframe, place it against a function here so it stays attached when the surface
is tuned.

Frame
-----
    +X  aft   (nose at X=0, tail at X=LENGTH)
    +Y  left  (port)
    +Z  up
    Z=0 is the ground plane; the aircraft sits on its gear.

Units are MILLIMETRES (repo default).  Real-world metres are converted once,
here, so the rest of the model reads in mm like every other repo part.

Dimensions and their source
---------------------------
Length 62 ft 8.5 in (19.11 m), span 64 ft 1.5 in (19.55 m) at 20 deg, 38 ft
2.5 in (11.65 m) at 68 deg, height 16 ft (4.88 m), wing area 565 sq ft --
Heatblur F-14 NATOPS-derived manual and flugzeuginfo.net, cross-checked against
the Smithsonian NASM F-14D(R) record.  Planform stations, glove sweep, inlet
wall offsets, fin cant and the section evolution were measured off the F-14D
general-arrangement drawing (Wikimedia Commons ``File:F-14D.jpg``, 3028x4863)
by thresholding the ink and reading the silhouette column by column; that
extraction put the swept span within 0.8 % of the published figure, which is
what sets the confidence on the derived numbers.

The blended body
----------------
The Tomcat is ONE continuous lifting body, not a fuselage with nacelles bolted
on.  So the airframe skin is a single multi-section loft: at every station a
full-width closed section is generated by SMOOTHLY BLENDING the component
volumes that exist there -- forebody, gloves, nacelles, the flat pancake tunnel,
the dorsal spine.  Blending happens in the section maths (:func:`smax` /
:func:`smin`), which means the glove-to-fuselage and nacelle-to-pancake
transitions are continuous BY CONSTRUCTION.  There is no fillet anywhere in the
primary surface, and there is nothing to "join".
"""

