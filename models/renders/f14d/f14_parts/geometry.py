def smax(a, b, k):
    """Smooth maximum with COMPACT support.  ``k`` is the blend width in mm.

    Cubic polynomial with compact support, NOT softplus/log-sum-exp.  Softplus
    is C-inf but its curvature is unbounded as k shrinks and it perturbs the
    surface everywhere; the blend where the inlet bridge met the forebody flank
    came out as a near-corner that no amount of extra sampling could resolve --
    97 samples per section were no better than 53, because the corner is in the
    function, not the sampling.

    The cube matters.  The obvious quadratic blend (``h*(1-h)``) is only C1, so
    curvature JUMPS at the edge of the blend band -- and a curvature jump on a
    specular surface draws a visible line, which put a crease down the full
    length of the aft fuselage at every feature rail.  ``h**3`` has zero first
    AND second derivative where the blend meets plain max(), so the transition
    is invisible.  Exactly max() outside |a-b| < k; adds at most k/6.
    """
    if k <= 1e-9:
        return max(a, b)
    h = max(k - abs(a - b), 0.0) / k
    return max(a, b) + h * h * h * k / 6.0


def smin(a, b, k):
    return -smax(-a, -b, k)


def smax_all(values, k):
    it = iter(values)
    out = next(it)
    for v in it:
        out = smax(out, v, k)
    return out


def smin_all(values, k):
    it = iter(values)
    out = next(it)
    for v in it:
        out = smin(out, v, k)
    return out


def clamp(v, lo, hi):
    return lo if v < lo else hi if v > hi else v


def smoothstep(edge0, edge1, x):
    if edge1 == edge0:
        return 0.0 if x < edge0 else 1.0
    t = clamp((x - edge0) / (edge1 - edge0), 0.0, 1.0)
    return t * t * (3.0 - 2.0 * t)


def lerp(a, b, t):
    return a + (b - a) * t


def _smooth(pts, passes=2):
    """Light smoothing of a MEASURED control curve, endpoints pinned.

    The station data was read off a scanned drawing, so it carries about a
    pixel of noise -- roughly +-8 mm at this scale.  A monotone interpolant
    reproduces that noise faithfully, and a loft through it puts a visible
    ripple down the fuselage.  Two passes of a [1,2,1] kernel remove the
    measurement noise while leaving the shape, which is metres, untouched.
    """
    out = [(x, v) for x, v in pts]
    for _ in range(passes):
        new = [out[0]]
        for i in range(1, len(out) - 1):
            v = 0.25 * out[i - 1][1] + 0.5 * out[i][1] + 0.25 * out[i + 1][1]
            new.append((out[i][0], v))
        new.append(out[-1])
        out = new
    return out


_SLOPE_CACHE = {}


def _slopes(pts):
    """Fritsch-Carlson (PCHIP) tangents for a control curve.

    NOT smoothstep between knots.  Smoothstep has ZERO derivative at BOTH ends
    of every interval, so a curve built from it is flat at each control point
    and steep between them -- a staircase.  Lofting through such curves put a
    visible ripple down the whole fuselage: every knot became a crease.  PCHIP
    is C1 with sensible tangents and cannot overshoot, so control points stay
    control points instead of becoming features.
    """
    key = id(pts)
    hit = _SLOPE_CACHE.get(key)
    if hit is not None and hit[0] is pts:
        return hit[1]
    n = len(pts)
    if n < 2:
        return [0.0] * n
    h = [pts[i + 1][0] - pts[i][0] for i in range(n - 1)]
    delta = [(pts[i + 1][1] - pts[i][1]) / h[i] if h[i] else 0.0 for i in range(n - 1)]
    m = [0.0] * n
    m[0] = delta[0]
    m[-1] = delta[-1]
    for i in range(1, n - 1):
        if delta[i - 1] * delta[i] <= 0.0:
            m[i] = 0.0                       # local extremum: flat, no overshoot
        else:
            w1 = 2.0 * h[i] + h[i - 1]
            w2 = h[i] + 2.0 * h[i - 1]
            m[i] = (w1 + w2) / (w1 / delta[i - 1] + w2 / delta[i])
    _SLOPE_CACHE[key] = (pts, m)
    return m


def _curve(pts, x):
    """Monotone piecewise-cubic through (x, value) control points."""
    if x <= pts[0][0]:
        return pts[0][1]
    if x >= pts[-1][0]:
        return pts[-1][1]
    m = _slopes(pts)
    lo, hi = 0, len(pts) - 1
    while hi - lo > 1:                         # binary search the interval
        mid = (lo + hi) // 2
        if pts[mid][0] <= x:
            lo = mid
        else:
            hi = mid
    x0, v0 = pts[lo]
    x1, v1 = pts[lo + 1]
    h = x1 - x0
    t = (x - x0) / h
    t2, t3 = t * t, t * t * t
    return (v0 * (2 * t3 - 3 * t2 + 1) + m[lo] * h * (t3 - 2 * t2 + t)
            + v1 * (-2 * t3 + 3 * t2) + m[lo + 1] * h * (t3 - t2))


