def stations():
    """The x stations the skin is lofted through."""
    key = [
        (0.0, 0.130 * G.M),                       # radome tip: dense
        (0.60 * G.M, 0.260 * G.M),
        (2.00 * G.M, 0.400 * G.M),
        (3.40 * G.M, 0.320 * G.M),                # windscreen
        (5.00 * G.M, 0.260 * G.M),                # canopy
        (6.10 * G.M, 0.120 * G.M),                # inlet lip: dense, the shape
        (6.55 * G.M, 0.240 * G.M),                # changes fastest here
        (8.20 * G.M, 0.320 * G.M),
        (9.20 * G.M, 0.420 * G.M),
        (11.00 * G.M, 0.520 * G.M),
        (13.50 * G.M, 0.520 * G.M),
        (15.80 * G.M, 0.360 * G.M),
        (16.90 * G.M, 0.220 * G.M),               # beavertail
        (X_SKIN_AFT, 0.0),
    ]
    xs, x = [0.0], 0.0
    i = 0
    while x < X_SKIN_AFT - 1e-6:
        while i < len(key) - 1 and x >= key[i + 1][0]:
            i += 1
        step = key[i][1]
        if i < len(key) - 1 and key[i + 1][1] > 0:
            t = (x - key[i][0]) / max(key[i + 1][0] - key[i][0], 1.0)
            step = G.lerp(key[i][1], key[i + 1][1], G.clamp(t, 0.0, 1.0))
        x = min(x + step, X_SKIN_AFT)
        xs.append(x)
    return xs


if __name__ == "__main__":
    xs = stations()
    print(f"{len(xs)} stations, {xs[0]:.1f} .. {xs[-1]:.1f} mm")
    for x in (0.2 * G.M, 1.5 * G.M, 3.5 * G.M, 5.5 * G.M, 6.5 * G.M,
              8.0 * G.M, 10.0 * G.M, 13.0 * G.M, 16.0 * G.M, 18.0 * G.M,
              19.0 * G.M):
        pts = section_points(x)
        w = outer_half_width(x)
        zs = [p[1] for p in pts]
        print(f"x={x/G.M:6.2f} m  pts={len(pts):3d}  halfwidth={w/G.M:5.3f} "
              f"z {min(zs)/G.M:+6.3f}..{max(zs)/G.M:+6.3f}")
