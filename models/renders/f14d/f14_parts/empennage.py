VENT_C = math.radians(VENT_CANT)
VENT_SIN, VENT_COS, VENT_TAN = math.sin(VENT_C), math.cos(VENT_C), math.tan(VENT_C)
Z_VENT_REF = _skin_bot(0.5 * (VENT_LE_ROOT + VENT_TE_ROOT), G.Y_VENTRAL)
VENT_N = 30


def _vent_le(h):
    return VENT_LE_ROOT + h * math.tan(math.radians(VENT_LE_SWEEP))


def _vent_te(h):
    return VENT_TE_ROOT + h * math.tan(math.radians(VENT_TE_SWEEP))


def _vent_plane(h, side):
    origin = (_vent_le(h), side * (G.Y_VENTRAL + h * VENT_TAN), Z_VENT_REF - h)
    return frame(origin, (1.0, 0.0, 0.0), (0.0, side * VENT_SIN, -VENT_COS))


VENT_STATIONS = [-VENT_BURY, -20.0, 70.0, 165.0, 260.0, 350.0, 425.0, 470.0,
                 498.0, 512.0, G.VENTRAL_HEIGHT]
VENT_TIP_ROUND = 62.0


def _ventral(side):
    faces = []
    for h in VENT_STATIONS:
        c = _vent_te(h) - _vent_le(h)
        t = G.clamp(h / G.VENTRAL_HEIGHT, 0.0, 1.0)
        thk = G.lerp(VENT_THICK_ROOT, VENT_THICK_TIP, t)
        d = G.VENTRAL_HEIGHT - h
        if d < VENT_TIP_ROUND:
            q = (VENT_TIP_ROUND - d) / VENT_TIP_ROUND
            thk *= math.sqrt(max(0.0, 1.0 - (0.975 * q) ** 2))
        pts = biconvex_points(thk / c, c, n=VENT_N, le_round=0.04)
        faces.append(_aerofoil_face(_vent_plane(h, side), pts, VENT_N))
    return P.style(loft(faces), "ventral_fin", P.GREY_LIGHT)


def _ventral_fairing(side):
    """Small skirt where the ventral root meets the nacelle underside."""
    xs = [15.960, 16.100, 16.240, 16.420, 16.640, 16.880, 17.120, 17.320,
          17.460, 17.580]
    reach, rise, sink = 0.130 * M, 0.062 * M, 0.075 * M
    faces = []
    for xm in xs:
        x = xm * M
        fade = (G.smoothstep(15.960 * M, 16.320 * M, x)
                * (1.0 - G.smoothstep(17.320 * M, 17.580 * M, x)))
        r = G.lerp(0.030 * M, reach, fade)
        ri = rise * fade
        wall = max(0.010 * M, 0.5 * G.lerp(VENT_THICK_ROOT, VENT_THICK_TIP, 0.0)
                   * math.sin(math.pi * G.clamp((x - VENT_LE_ROOT)
                                                / (VENT_TE_ROOT - VENT_LE_ROOT),
                                                0.02, 0.98) ** 0.9) - 0.008 * M)
        ds = [0.0, 0.5 * wall] + [wall + r * (0.5 - 0.5 * math.cos(math.pi * i / 9))
                                  for i in range(10)]
        dys = [-d for d in reversed(ds[1:])] + ds
        d_max = wall + r
        top, bot = [], []
        for dy in dys:
            y = side * G.Y_VENTRAL + dy
            z0 = _skin_bot(x, y)
            if z0 is None:
                z0 = Z_VENT_REF
            d = abs(dy)
            if d <= wall:
                delta = ri
            else:
                s = G.clamp((wall + r - d) / r, 0.0, 1.0)
                delta = ri * (1.0 - math.sqrt(max(0.0, 1.0 - s * s)))
            edge = 0.014 * M + 0.040 * M * (1.0 - fade)
            lower = -delta + edge * (1.0 - G.clamp((d_max - d) / max(r, 1.0), 0.0, 1.0))
            top.append(Vector(x, y, z0 + sink))
            bot.append(Vector(x, y, z0 + lower))
        # collapse the two curves onto each other at the outer edge
        bot[0] = Vector(bot[0].X, bot[0].Y, top[0].Z)
        bot[-1] = Vector(bot[-1].X, bot[-1].Y, top[-1].Z)
        faces.append(Face(Wire([Spline(*top).edge(), Spline(*bot).edge()])))
    return P.style(loft(faces), "ventral_fairing", P.GREY_LIGHT)


