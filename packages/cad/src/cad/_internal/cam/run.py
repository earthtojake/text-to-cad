"""What a CAM job does, end to end: ``cad.<type>.plan`` (``cad._internal.cam.operation``) calls :func:`list_features`
with no job and :func:`plan_job` with one.

``plan_job`` is the pipeline: parse the job -> find FreeCAD -> read the part and its features -> per setup: its work
coordinates, each operation's faces, depths and feeds, and the reach checks -> FreeCAD plans and posts the setup's
operations (``cad.freecad``) -> the moves are read back and checked against the part -> the verdict -> its results
written into the folder ``out``: ``result.json`` (the :class:`CamResult` returned, as ``--json`` prints it),
``result.glb`` (the part, the stock and the toolpaths) and, when nothing is an error, the G-code, each staged in a
folder inside ``out`` and moved into place only once every one is written.

A plan with an error fails, and writes ``result.json`` and ``result.glb`` (they say what is wrong, and where) and no
G-code; the G-code an earlier plan wrote into the folder, as its ``result.json`` lists it, is removed, so no "ready"
program stands beside a plan that is not. A job that cannot run at all (:class:`CamJobError`, no FreeCAD) fails too,
and writes nothing, not even its folder.
"""

from __future__ import annotations

import json
import math
import os
import shutil
import tempfile
import time
from dataclasses import dataclass, replace
from pathlib import Path

from cad._internal.atomic_replace import replace_atomic
