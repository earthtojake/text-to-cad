from cad._internal.cam.job_errors import CamJobError
from cad._internal.cam.log import CamLog
from cad.results import CamResult

__all__ = ["RESULT_GLB", "RESULT_JSON", "headline", "list_features", "plan_job"]

#: What a plan writes into its folder beside the G-code: the answer, and the part, stock and toolpaths any viewer opens.
RESULT_JSON, RESULT_GLB = "result.json", "result.glb"

_SAFETY = ("Generated by text-to-cad with FreeCAD; not proven on a machine. Air-cut or single-block it first, and check the "
           "work offset and every tool length.")


def job_finding(message: str, kind: str = "job") -> dict:
    """A job that cannot run, as the one error finding its result carries."""
    what = ("install FreeCAD as the message says and plan again" if kind == "freecad"
            else "change the job (or the --occurrence) as the message says and plan again")
    return finding("job", "error", kind, message, f"the job was refused before anything was planned; nothing was "
                   f"written: {what}")


def _internal(exc: Exception, what: str) -> dict:
    return finding("job", "error", "internal_error", f"CAM failed {what} ({type(exc).__name__}: "
                   f"{str(exc)[:200]})", "this is a bug in the CAD server, not in the part: report it with the part")


def _stopped(named: Path, found: dict) -> CamResult:
    """What a job that could not run answers: its one error finding, nothing written."""
    return CamResult(ok=False, path=named, findings=(as_check_finding(found),))


def list_features(target: Path, *, occurrence: str | None = None, verbose: bool = False,
                  label: Path | None = None) -> CamResult:
    """What a job can name on the part, written nowhere. ``label`` is what the result names the source as where
    ``target`` is not it (a model's id, its ``.xbf`` written for the job)."""
    from cad._internal.cam.features import read_features
    from cad._internal.cam.part import read_part

    document = Path(target)
    named = Path(label) if label is not None else document
    logger = CamLog(verbose=verbose)
    try:
        with logger.timed("read part"):
            part = read_part(document, occurrence=occurrence)
        with logger.timed("read features"):
            reading = read_features(part)
    except CamJobError as exc:
        return _stopped(named, job_finding(str(exc)))
    except OSError as exc:
        return _stopped(named, job_finding(f"{named.name} could not be read: {exc.strerror or exc}"))
    except ModuleNotFoundError:
        raise  # the integration this process lacks: the operation says which
    except Exception as exc:  # noqa: BLE001 - a bug in the CAD server is a refusal that says so, never a traceback
        return _stopped(named, _internal(exc, "reading this part"))
    low, high = part.bbox
    bbox = {"min": [round(float(v), 4) + 0.0 for v in low], "max": [round(float(v), 4) + 0.0 for v in high],
            "size": [round(float(b - a), 4) + 0.0 for a, b in zip(low, high)]}
    summary = (f"{named.name}: {len(reading['faces'])} faces, {len(reading['holes'])} holes, "
               f"{len(reading['floors'])} floors")
    return CamResult(ok=True, path=named, summary=summary, measurements={"bbox_mm": bbox},
                     occurrence=part.occurrence, faces=tuple(reading["faces"]), holes=tuple(reading["holes"]),
                     floors=tuple(reading["floors"]))


