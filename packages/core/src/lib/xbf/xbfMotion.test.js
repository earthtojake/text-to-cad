// The page's motions against the engine's GLB bake of the same motions: `__fixtures__/arm` is a
// document with every kind of motion, and the GLB the engine exports from it (`cadgen export
// XBF/arm.xbf arm.glb`). The arm: a base, a link on revolute `elbow` (-10..120), a tip on prismatic
// `slide` (0..80) along it, a door on revolute `door` (0..120) and a drawer on prismatic `drawer`
// (0..40), the two coupled as `open` (door 90, drawer 30 per unit); configurations `raised`
// (elbow 90) and `ajar` (open 0.5); and four motions: `lift` (cubic waypoints, one a
// configuration), `swing` (cubic waypoints of the coupling), `wave` (a linear sweep) and `nod` (a
// function, kept as its samples). It is regenerated by building that model (the engine's motion
// test's `ARM`, with the door and the drawer added) with `cadgen.engine.build`, exporting its xbf
// to GLB (`cadgen.engine.export.translate`) and saving `document.Loaded(xbf).structure()`, its
// `path` and `version` made neutral.
//
// The bake keys every moving placement at true forward kinematics (each key's value), and between
// keys a CUBICSPLINE within the baker's tolerance of it. So the page's values at a key's time,
// posed by its forward kinematics, are the key, and between keys the GLB's curve is within that
// tolerance of them.
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";

import { xbfCouplingValues, xbfKinematics, xbfPosedMatrices } from "./xbfKinematics.js";
import { xbfMotionEase, xbfMotions, xbfMotionTimeline } from "./xbfMotion.js";

const FIXTURE = path.join(path.dirname(fileURLToPath(import.meta.url)), "__fixtures__", "arm");
const STRUCTURE = JSON.parse(fs.readFileSync(path.join(FIXTURE, "structure.json"), "utf8"));
const KINEMATICS = xbfKinematics(STRUCTURE);
// The baker's tolerances (`mechanism.LINEAR_TOLERANCE`, `ANGULAR_TOLERANCE`): a thousandth of the
// model's size (its diagonal, about 230 mm; 200 here, the stricter) and a milliradian.
const LINEAR = 1e-3 * 200, ANGULAR = 1e-3;

/** A GLB's JSON, and its accessors as rows of float32 values. */
function readGlb(file) {
  const data = fs.readFileSync(file);
  const length = data.readUInt32LE(12);
  const gltf = JSON.parse(data.subarray(20, 20 + length).toString("utf8"));
  const binary = data.subarray(28 + length, 28 + length + data.readUInt32LE(20 + length));
  const read = (at) => {
    const accessor = gltf.accessors[at];
    const view = gltf.bufferViews[accessor.bufferView];
    const width = { SCALAR: 1, VEC3: 3, VEC4: 4 }[accessor.type];
    const floats = new Float32Array(binary.buffer.slice(binary.byteOffset + (view.byteOffset || 0) + (accessor.byteOffset || 0)), 0, accessor.count * width);
    return Array.from({ length: accessor.count }, (_, row) => Array.from(floats.subarray(row * width, row * width + width)));
  };
  return { gltf, read };
}

/** glTF's CUBICSPLINE at `t`: `rows` three per key (in-tangent, value, out-tangent). */
function cubic(times, rows, t) {
  let at = 0;
  while (at < times.length - 2 && times[at + 1] <= t) at += 1;
  const span = times[at + 1] - times[at], s = (t - times[at]) / span;
  const [a, b] = [rows[at * 3 + 1], rows[(at + 1) * 3 + 1]], [out, into] = [rows[at * 3 + 2], rows[(at + 1) * 3]];
  return a.map((_, k) => (2 * s ** 3 - 3 * s ** 2 + 1) * a[k] + span * (s ** 3 - 2 * s ** 2 + s) * out[k]
    + (-2 * s ** 3 + 3 * s ** 2) * b[k] + span * (s ** 3 - s ** 2) * into[k]);
}

/** A column-major matrix's rotation as a unit quaternion (x, y, z, w). */
function quaternion(m) {
  const [m00, m10, m20, , m01, m11, m21, , m02, m12, m22] = m;
  const trace = m00 + m11 + m22;
  let q;
  if (trace > 0) { const s = Math.sqrt(trace + 1) * 2; q = [(m21 - m12) / s, (m02 - m20) / s, (m10 - m01) / s, s / 4]; }
  else if (m00 > m11 && m00 > m22) { const s = Math.sqrt(1 + m00 - m11 - m22) * 2; q = [s / 4, (m01 + m10) / s, (m02 + m20) / s, (m21 - m12) / s]; }
  else if (m11 > m22) { const s = Math.sqrt(1 + m11 - m00 - m22) * 2; q = [(m01 + m10) / s, s / 4, (m12 + m21) / s, (m02 - m20) / s]; }
  else { const s = Math.sqrt(1 + m22 - m00 - m11) * 2; q = [(m02 + m20) / s, (m12 + m21) / s, s / 4, (m10 - m01) / s]; }
  const norm = Math.hypot(...q);
  return q.map(value => value / norm);
}

/** The angle between two rotations given as quaternions (radians). */
function turn(a, b) {
  const norm = Math.hypot(...a) * Math.hypot(...b);
  return 2 * Math.acos(Math.min(1, Math.abs(a.reduce((sum, value, k) => sum + value * b[k], 0)) / norm));
}

test("the page's motions are the document's, by name, with their durations and interpolations", () => {
  assert.deepEqual(xbfMotions(KINEMATICS), [
    { name: "lift", duration: 3, ease: "cubic" }, { name: "nod", duration: 6, ease: "linear" },
    { name: "swing", duration: 2.5, ease: "cubic" }, { name: "wave", duration: 2, ease: "linear" }
  ]);
  assert.deepEqual(xbfMotions(null), []);
  assert.throws(() => xbfMotionTimeline(KINEMATICS, "dance"), /no motion 'dance'/);
  // Synchronous: eased in and out, at rest at both ends of a step, halfway at its middle.
  assert.equal(xbfMotionEase("cubic", 0.5), 0.5);
  assert.ok(xbfMotionEase("cubic", 0.1) < 0.1 && xbfMotionEase("cubic", 0.9) > 0.9);
  assert.equal(xbfMotionEase("linear", 0.1), 0.1);
});

test("a motion's values: its keys, eased between them, the rest as built, finite at both ends", () => {
  const lift = xbfMotionTimeline(KINEMATICS, "lift");
  assert.deepEqual(lift.labels, ["elbow", "slide"]);
  assert.deepEqual(lift.values(1.5).elbow, [90], "a configuration's key");
  assert.deepEqual(lift.values(0.75).elbow, [45], "a synchronous step is halfway at its middle");
  assert.ok(Math.abs(lift.values(0.375).elbow[0] - 90 * xbfMotionEase("cubic", 0.25)) < 1e-9);
  assert.deepEqual(lift.values(0.75).door, [0], "a pair the motion does not move stays as built");
  assert.deepEqual(lift.values(-1), lift.values(0), "before the clip, its first key");
  assert.deepEqual(lift.values(99), lift.values(3), "after it, its last: a motion is a finite clip");
  const wave = xbfMotionTimeline(KINEMATICS, "wave");
  assert.ok(Math.abs(wave.values(0.5).elbow[0] - 7.5) < 1e-9, "a linear sweep, constant speed");
  // A coupling's joints keep its ratios all the way.
  const swing = xbfMotionTimeline(KINEMATICS, "swing");
  for (const t of [0.2, 0.5, 1, 1.7, 2.5]) {
    const values = swing.values(t);
    const at = xbfCouplingValues(KINEMATICS, values).open;
    assert.ok(Math.abs(values.door[0] - 90 * at) < 1e-9 && Math.abs(values.drawer[0] - 30 * at) < 1e-9, `swing at ${t}`);
  }
  assert.deepEqual(swing.values(2.5), { ...swing.values(2.5), door: [45], drawer: [15] }, "ends at `ajar`");
});

test("posed by the page's forward kinematics, every motion is the engine's GLB bake at its keys and within its tolerance between them", () => {
  const { gltf, read } = readGlb(path.join(FIXTURE, "arm.glb"));
  const instances = new Map(STRUCTURE.instances.map((instance, at) => [instance.path, at]));
  const root = STRUCTURE.tree.name;
  assert.deepEqual(gltf.animations.map(animation => animation.name), xbfMotions(KINEMATICS).map(motion => motion.name));
  const report = {};
  for (const animation of gltf.animations) {
    const timeline = xbfMotionTimeline(KINEMATICS, animation.name);
    assert.equal(animation.extras.cadgen.duration, timeline.duration);
    const times = read(animation.samplers[0].input).map(([t]) => t);
    const posed = new Map();
    const at = (t) => { if (!posed.has(t)) posed.set(t, xbfPosedMatrices(STRUCTURE, timeline.values(t))); return posed.get(t); };
    const worst = { keys: [0, 0], between: [0, 0] };
    for (const channel of animation.channels) {
      const index = instances.get(`${root}/${gltf.nodes[channel.target.node].name}`);
      assert.ok(index != null, gltf.nodes[channel.target.node].name);
      const rows = read(animation.samplers[channel.sampler].output);
      const apart = (got, t) => {
        const truth = at(t)[index];
        return channel.target.path === "translation" ? Math.hypot(...got.map((value, k) => value - truth[12 + k])) : turn(got, quaternion(truth));
      };
      const slot = channel.target.path === "translation" ? 0 : 1;
      times.forEach((t, key) => { worst.keys[slot] = Math.max(worst.keys[slot], apart(rows[key * 3 + 1], t)); });
      for (let key = 0; key < times.length - 1; key += 1) {
        for (let step = 1; step < 8; step += 1) {
          const t = times[key] + (times[key + 1] - times[key]) * step / 8;
          worst.between[slot] = Math.max(worst.between[slot], apart(cubic(times, rows, t), t));
        }
      }
    }
    report[animation.name] = { keys: times.length, ...worst };
    // At a key: the bake's float32 of the same forward kinematics.
    assert.ok(worst.keys[0] < 1e-3 && worst.keys[1] < 1e-5, `${animation.name} at its keys: ${JSON.stringify(worst)}`);
    // Between keys: the bake's curve, within its tolerance of the page's values (half again
    // between the bake's own checks, as the engine's test allows).
    assert.ok(worst.between[0] < LINEAR * 1.5 && worst.between[1] < ANGULAR * 1.5, `${animation.name} between keys: ${JSON.stringify(worst)}`);
  }
  if (process.env.XBF_MOTION_PARITY_REPORT) console.log(JSON.stringify(report));
});
