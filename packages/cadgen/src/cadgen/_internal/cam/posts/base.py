"""The ``Post`` base every controller subclasses: render one setup's Toolpath IR as G-code text.

A post is a small class (one module per controller under ``posts/``, registered in ``posts/__init__.py``)::

    class GrblPost(Post):
        name = "grbl"; kinds = ("mill", "router", "laser"); extension = ".nc"
        accepts_arcs = True                 # G2/G3 (else arcs are posted as short lines)
        canned_cycles = frozenset()         # cycles it posts natively (else the IR's expansion is posted)
        tool_changer = False                # M6 (else one program per tool: split_by_tool)
        split_by_tool = True                # render_tool_files(program): one complete file per tool

    text = post.render(program)             # deterministic: no timestamps, fixed number format

:class:`Program` is what a post renders: one setup's toolpath (WCS), its tools, the machine and a few names. The
output always opens with the safety comment block (:meth:`Post.header`): generated by cadgen and its version, NOT
proven on a machine, air-cut or single-block it first, what to verify for the machine kind (the work offset and every
tool length on a mill; the focus on a laser; the torch heights on a plasma table...), and one line per tool with the
speeds it runs at, its fastest feed and its fastest plunge (``T1: 6 mm flat: 12000 rpm, feed 1990 mm/min``); a
program with a fine bore that shifts its bar, or a back bore, says which way, and so where the bar's tip must point at
the orient.

The base walks the IR in order with modal state (only changed words are written) and calls overridable hooks for
each event and move: :meth:`Post.preamble`, :meth:`Post.on_setup` (work offset, a 3+2 rotary position),
:meth:`Post.on_tool`, :meth:`Post.on_spindle`, :meth:`Post.on_coolant`, :meth:`Post.on_stop`, :meth:`Post.on_beam`,
:meth:`Post.cycle_lines` (Fanuc-style G81/G82/G83/G73/G84/G85, used when the cycle is in ``canned_cycles``),
:meth:`Post.expansion` (a cycle posted as its moves), :meth:`Post.footer`. :func:`fit_arcs` fits lines and G2/G3
arcs to runs of feed moves at one feed, no point of the run straying past the tolerance; a post that accepts arcs
uses it (``fit_arcs_to_lines``), so a straight run posts as one line, an offset pocket's rounded corners as arcs, and
(``helical_arcs``, Z posted) a densified helix as one helical G2/G3, not as hundreds of lines.

What the walk does for safety, whatever the controller:

- refuses a number no controller should get (:meth:`Post.validate`): a coordinate that is not finite, a feed that
  is not positive, a spindle speed or cycle number that is not a number, naming the setup, operation and move; and a
  spindle speed that posts as ``S0`` (:class:`PostRefusal`, on its operation).
- refuses (:class:`PostRefusal`, on the operation) a cycle it would post as moves that cannot do the cycle's job: a
  tap (the feed would not follow the spindle and the tap would break: thread mill it, or use a post that taps), and a
  fine bore that shifts its bar, or a back bore, on a controller that cannot orient its spindle
  (:attr:`Post.orient_lines`, the M19 written at each oriented stop before a shift where it can). A tap cycle's F is
  the posted S times the pitch.
- a depth is never posted deeper than planned: a cutting move's Z rounds up at the post's resolution and a canned
  cycle's Z toward its R plane; every other number rounds to nearest.
- the first motion of the program and after every tool change (the tool is at the top, its XY unknown): rotary
  axes first, then X Y at that height, then the tool length (``G43 Z H``: :meth:`Post.entry_length`), then down.
- a rapid that turns a rotary axis: refused below the clearance height (or, under tool centre point control,
  straight out of a cut), else posted as retract, turn, X Y, Z.
- after a stop (M0/M1) the spindle and coolant are switched back on before the next move; after a tool change that
  stopped the coolant, the coolant; a spindle start from standstill is followed by ``G4`` for the job's
  ``machine.spindle_spinup_s`` on every post (:meth:`Post.spinup`; when the job sets none, the post's own default:
  none but on GRBL); a cutting move after a tool change with the spindle stopped is refused.
- coolant: a mode the controller has a code for (:attr:`Post.coolant_codes`) is that code, with the mode in effect
  switched off first; a mode it has none for is a comment telling the operator to switch it on (and off) by hand,
  never another mode's code.
- an arc whose posted end equals its posted start is not a full circle: it posts as a line; an arc whose posted
  start and end lie at different distances from its posted centre is refused.
- a native canned cycle is called from its initial level (G98 returns there).
- comments hold only letters, digits, space and ``. , : / + - _ = * # ' "``: GRBL reads bytes of 0x80 and up, and
  ``!`` ``~`` ``?``, as realtime commands even inside a comment, ``%`` ends a Fanuc tape and ``;`` opens a comment.
  They wrap to 70 characters.

Stdlib at import; numpy inside.
"""

