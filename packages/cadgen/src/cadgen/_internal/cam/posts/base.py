        tool = next((program.tools[e.data["tool"]] for e in program.toolpath.events if e.kind == "tool"), None)
        origin = program.setup.origin
        where = {"stock-top-center": "on the stock top", "stock-top-corner": "on the stock top",
                 "part-top-center": "on the part top"}.get(origin if isinstance(origin, str) else "",
                                                           "at the setup's Z zero")
        first = program.file_index == 0
        load = f"load {self.tool_label(tool)}" if tool is not None else "load its tool"
        zero = (f"zero X and Y at the setup's origin and Z {where}" if first else
                f"keep X and Y, zero Z {where} with this tool")
        return (f"File {program.file_index + 1} of {program.file_count}: {load}, {zero}, then run it. Run the files "
                "in order.")

