def _duration_words(seconds: float) -> str:
    """``42 s``, ``4 min``, ``1 h 05 min``: rounded first, so 59.6 s is ``1 min``."""
    whole = max(1, round(seconds))
    if whole < 60:
        return f"{whole} s"
    minutes = max(1, round(seconds / 60))
    if minutes < 60:
        return f"{minutes} min"
    hours, rest = divmod(minutes, 60)
    return f"{hours} h {rest:02d} min"


def headline(errors: int, seconds: float, tools: int) -> str:
    """``Ready to cut · 42 min · 3 tools`` or ``2 to fix · 42 min · 3 tools``."""
    head = "Ready to cut" if errors == 0 else f"{errors} to fix"
    return f"{head} · {_duration_words(seconds)} · {tools} tool{'s' if tools != 1 else ''}"


def _glb_path(document: Path, out_dir: Path | None) -> Path:
    folder = Path(out_dir) if out_dir is not None else document.parent
    return folder / f"{document.stem}.cam.glb"


def _glb_cam(path: Path) -> dict | None:
    """The plan a cadgen GLB carries (``scenes[0].extras.cam``), read from its JSON chunk alone; None for anything
    else (not there, not a GLB, not cadgen's)."""
    from cadgen._internal.primitive_mesh import GLB_JSON_CHUNK, GLB_MAGIC

    try:
        with open(path, "rb") as handle:
            head = handle.read(20)
            if len(head) < 20:
                return None
            magic, _, _, length, kind = struct.unpack("<IIIII", head)
            if magic != GLB_MAGIC or kind != GLB_JSON_CHUNK or length > 64 * 1024 * 1024:
                return None
            document = json.loads(handle.read(length))
    except (OSError, ValueError, RecursionError, struct.error):
        return None
    scenes = document.get("scenes") if isinstance(document, dict) else None
    extras = scenes[0].get("extras") if isinstance(scenes, list) and scenes and isinstance(scenes[0], dict) else None
    cam = extras.get("cam") if isinstance(extras, dict) else None
    return cam if isinstance(cam, dict) and cam.get("generator") == "cadgen cam" else None


def _previous_posts(glb_path: Path, stem: str) -> list[Path]:
    """The posted files an earlier plan's GLB at ``glb_path`` lists: plain names beside it, named for this document as
    a plan names a program (``<stem>.<setup>[.<n>-<tool>]<ext>``, a post's extension), so a name the GLB carries is
    never taken for one of the person's own files (``bracket.step``)."""
    from cadgen._internal.cam.job import POSTS

    cam = _glb_cam(glb_path) if glb_path.is_file() else None
    posts = cam.get("posts") if cam else None
    extensions = tuple({post["ext"] for post in POSTS.values()})
    out = []
    for entry in posts if isinstance(posts, list) else ():
        name = entry.get("file") if isinstance(entry, dict) else None
        if (isinstance(name, str) and name.startswith(f"{stem}.") and name.endswith(extensions)
                and "/" not in name and "\\" not in name):
            out.append(glb_path.parent / name)
    return out


def _relative(target: Path, start: Path) -> str:
    try:
        return Path(os.path.relpath(Path(target).resolve(), Path(start).resolve())).as_posix()
    except ValueError:  # another drive on Windows
        return Path(target).resolve().as_posix()


@dataclass(frozen=True)
class Frame:
    """A setup's work coordinates: the part turned so the tool comes down -Z (``sign`` -1 turns it over about X),
    then moved so the work zero is the origin."""

    sign: float
    origin: tuple[float, float, float]

    def to_setup(self, points):
        import numpy as np

        return np.asarray(points, dtype=float) * [1.0, self.sign, self.sign] - self.origin

    def to_part(self, points):
        import numpy as np

        return (np.asarray(points, dtype=float) + self.origin) * [1.0, self.sign, self.sign]

    def direction(self, vector):
        return None if vector is None else (vector[0], self.sign * vector[1], self.sign * vector[2])

    def matrix(self) -> list[list[float]]:
        """Part -> work coordinates' rotation, rows the work X, Y and Z in part coordinates."""
        return [[1.0, 0.0, 0.0], [0.0, self.sign, 0.0], [0.0, 0.0, self.sign]]

    def write_brep(self, shape, path: Path) -> None:
        from OCP.BRepTools import BRepTools
        from OCP.gp import gp_Ax1, gp_Dir, gp_Pnt, gp_Trsf, gp_Vec
        from OCP.TopLoc import TopLoc_Location

        turn, move = gp_Trsf(), gp_Trsf()
        if self.sign < 0:
            turn.SetRotation(gp_Ax1(gp_Pnt(0, 0, 0), gp_Dir(1, 0, 0)), math.pi)
        move.SetTranslation(gp_Vec(*(-v for v in self.origin)))
        # A located copy: the same faces in the same order, so FreeCAD's FaceN is cadgen's face N.
        BRepTools.Write_s(shape.wrapped.Moved(TopLoc_Location(move.Multiplied(turn))), str(path))


def _frame(setup, stock_low, stock_high) -> Frame:
    import numpy as np

    sign = 1.0 if setup.orientation == "+Z" else -1.0
    corners = np.array([stock_low, stock_high]) * [1.0, sign, sign]
    low, high = corners.min(axis=0), corners.max(axis=0)
    z = high[2] if setup.origin.startswith("stock-top") else low[2]
    xy = (low[:2] + high[:2]) / 2 if setup.origin.endswith("center") else low[:2]
    return Frame(sign=sign, origin=(float(xy[0]), float(xy[1]), float(z)))


def _setup_reach(direction: str, sign: float) -> str:
    return direction if sign > 0 or direction[1] != "Z" else ("-Z" if direction[0] == "+" else "+Z")


def plan_job(target: Path, *, job, occurrence: str | None = None, out_dir: Path | None = None,
             verbose: bool = False) -> CamPlanResult:
    from cadgen._internal.cam.freecad import FreecadMissingError, find_freecad
    from cadgen._internal.cam.job import parse_job
    from cadgen._internal.cam.part import read_part

    document = Path(target)
    started = time.perf_counter()
    logger = CamLog(verbose=verbose)
    try:
        parsed = parse_job(job)
        freecad = find_freecad()
        with logger.timed("read part"):
            part = read_part(document, occurrence=occurrence)
        return _plan(document, parsed, part, freecad, _glb_path(document, out_dir), logger, started)
    except CamJobError as exc:
        return CamPlanResult(ok=False, document=document, findings=(job_finding(str(exc)),))
    except FreecadMissingError as exc:
        return CamPlanResult(ok=False, document=document, findings=(job_finding(str(exc), "freecad"),))
    except OSError as exc:
        return CamPlanResult(ok=False, document=document, findings=(job_finding(
            f"{document.name} could not be read or a result could not be written: {exc.strerror or exc}"),))
    except Exception as exc:  # noqa: BLE001 - a bug in cadgen is a refusal that says so, never a traceback
        return CamPlanResult(ok=False, document=document, findings=(_internal(exc, "planning this job"),))


def _setup_z(frame, point) -> float:
    return float(frame.to_setup([point])[0][2])


def _final_depth(op, faces, holes, tool, frame, part_low_z: float, where: str) -> float | None:
    """The depth an operation is cut down to, in setup coordinates (None: FreeCAD's own reading). ``face``: the
    highest face it names. ``profile``: round the part's outline, or the faces it names down to the lowest of them (a
    blind feature's floor; the part's bottom ``outside`` a flat face, whose inside is its pocket's walls by now or
    refused by the reach check), and
    ``through_mm`` past the part's bottom where they reach it. ``drill``: each hole's depth. ``pocket`` and
    ``adaptive``: the floors they name. One operation cuts to one depth: faces that would need two are refused."""
    params = op.params
    if op.op == "face":
        return max(_setup_z(frame, info.center_mm) for info in faces)
    finals = set()
    if op.op == "profile":
        if not faces:
            return part_low_z - params["through_mm"]
        for info in faces:
            normal = frame.direction(info.normal)
            if normal is not None and normal[2] > 1 - 1e-6 and params["side"] == "outside":
                bottom = part_low_z         # a flat face's outline, cut through what stands under it
            else:
                bounds = info.bounds or (info.center_mm, info.center_mm)
                bottom = float(frame.to_setup(bounds)[:, 2].min())
            finals.add(round(part_low_z - params["through_mm"] if bottom <= part_low_z + 1e-3 else bottom, 4))
        what = "these faces end at different heights"
    elif op.op == "drill":
        for info in faces:
            hole = holes.get(info.ref)
            if hole is None:
                continue        # not a face of a hole: the reach check says so
            bottom = _setup_z(frame, hole["center_mm"]) - hole["depth_mm"]
            finals.add(round(bottom - params["through_mm"] - tool.tip_length_mm if hole["through"]
                             else bottom - hole.get("point_mm", 0.0), 4))
        what = "these holes are drilled to different depths"
    else:
        # FreeCAD cuts one operation to one depth: the higher floors would be cut down to the lowest.
        finals = {round(_setup_z(frame, info.center_mm), 4) for info in faces}
        what = "these floors are at different heights"
    if len(finals) > 1:
        raise CamJobError(f"{where}: {what} ({', '.join(f'{z:g}' for z in sorted(finals))}); {op.op} each in its "
                          "own operation")
    return finals.pop() if finals else None


def _floors_to_walls(faces, part, frame, where: str) -> tuple[list, dict[str, list[str]]]:
    """An inside profile runs along walls: a pocket's floor it names, facing the tool in this setup, stands for that
    pocket's walls (:func:`features.pocket_walls`). The faces it cuts, each once however it is named (a floor and its
    own walls together cut them once), and which walls each floor stood for. Any other flat face is kept, for the
    reach check to refuse."""
    from cadgen._internal.cam.features import pocket_walls

    out, floors = {}, {}
    for info in faces:
        facing = info.normal is not None and frame.direction(info.normal)[2] > 1 - 1e-6
        walls = pocket_walls(part, info.ordinal) if facing else None
        if walls:
            floors[info.ref] = walls
            for ref in walls:
                out.setdefault(ref, part.face(ref, where))
        else:
            out.setdefault(info.ref, info)
    return list(out.values()), floors


def _targets(op, faces, holes, final_z, frame, mesh, face_of_triangle, tool) -> list:
    """What the coverage check holds the operation to (:class:`checks.Target`): each hole a drill names (once, however
    many of its faces are named), each floor a pocket or adaptive names, each face a profile names, and each face a
    face operation faces, the whole of it (the tool runs out past the part's edges, so no corner is its to leave)."""
    from cadgen._internal.cam.checks import Target, face_edges, face_points

    if final_z is None:
        return []
    if op.op == "drill":
        out, seen = [], set()
        for info in faces:
            hole = holes.get(info.ref)
            if hole is None or hole["faces"][0] in seen:
                continue
            seen.add(hole["faces"][0])
            x, y, _ = frame.to_setup([hole["center_mm"]])[0]
            out.append(Target(ref=info.ref, final_z=final_z, axis_xy=(float(x), float(y))))
        return out
    vertices, triangles = mesh
    wall = op.op == "profile"
    return [Target(ref=info.ref, final_z=final_z, wall=wall, leave_mm=op.params.get("leave_mm", 0.0),
                   points=face_points(vertices, triangles, face_of_triangle == info.ordinal, max(0.25, tool.radius / 2)),
                   edges=None if wall or op.op == "face" else face_edges(vertices, triangles,
                                                                        face_of_triangle == info.ordinal))
            for info in faces]


def _plan(document, parsed, part, freecad, glb_path, logger, started) -> CamPlanResult:
    import numpy as np

    from cadgen._internal.cam import checks, freecad as runner, toolpath
    from cadgen._internal.cam.features import read_features, walls_in
    from cadgen._internal.cam.feeds import default_stepdown, for_op
    from cadgen._internal.cam.job import OPERATIONS, POSTS
    from cadgen._internal.cam.outputs import line_segments, write_glb

    timings: dict = {}
    machine, tools = parsed.machine, parsed.tools
    post = POSTS[machine.post]
    with logger.timed("read features"):
        reading = read_features(part)
    # Every face of a hole names it: its walls, its counterbore's wall and shoulder, its drawn point, its floor.
    holes = {ref: hole for hole in reading["holes"] for ref in hole["faces"]}
    ordinal_of = {info.ref: ordinal for ordinal, info in part.faces.items()}
    low, high = (np.asarray(v, dtype=float) for v in part.bbox)
    margin = parsed.stock.margin_mm
    stock_low = low - [margin[0], margin[1], 0.0]
    stock_high = high + [margin[0], margin[1], margin[2]]
    findings: list[dict] = []
    clamps: dict[tuple[str, str], list[dict]] = {}
    setups_out, operations_out, lines, posted = [], [], [], []
    clock = 0.0
    for setup in parsed.setups:
        frame = _frame(setup, stock_low, stock_high)
        mesh = (frame.to_setup(part.vertices), part.triangles)
        s_low, s_high = np.sort(frame.to_setup([stock_low, stock_high]), axis=0)
        part_z = mesh[0][:, 2]
        stock_top = float(s_high[2])
        specs, planned, rows, targets, floors_of = [], [], {}, {}, {}
        for op in setup.operations:
            tool = tools[op.tool]
            faces = [part.face(ref, f"{op.where}.faces") for ref in op.faces]
            if op.op == "profile" and op.params["side"] == "inside":
                faces, floors_of[op.index] = _floors_to_walls(faces, part, frame, f"{op.where}.faces")
            if op.op == "face" and not faces:
                faces = [info for info in part.faces.values() if info.normal is not None
                         and frame.direction(info.normal)[2] > 1 - 1e-6
                         and abs(float(frame.to_setup([info.center_mm])[0][2]) - float(part_z.max())) < 1e-3]
            turned = [replace(info, normal=frame.direction(info.normal)) for info in faces]
            turned_holes = {ref: dict(hole, reach=[_setup_reach(d, frame.sign) for d in hole["reach"]])
                            for ref, hole in holes.items()}
            final_z = _final_depth(op, faces, holes, tool, frame, float(part_z.min()), op.where) \
                if faces or op.op == "profile" else None
            flat = [info for info in turned if op.op == "profile" and op.params["side"] == "inside"
                    and info.normal is not None and abs(info.normal[2]) > 1 - 1e-6]
            found = checks.reach(op, turned, turned_holes, mesh, part.face_of_triangle, tool, stock_top, final_z,
                                 walls={info.ref: walls_in(part, info.ordinal) for info in flat})
            findings += found
            stepover = op.params.get("stepover")
            feeds = for_op(parsed.material, tool, OPERATIONS[op.op]["feeds"], machine,
                           stepover_mm=stepover * tool.diameter_mm if stepover else None, feed=op.params["feed"],
                           speed=op.params["speed"], plunge=op.params["plunge_mm_min"])
            for words in feeds.clamped:
                clamps.setdefault((tool.id, words), []).append({"operation": op.index})
            rows[op.index] = {
                "index": op.index, "setup": setup.id, "op": op.op, "plain": op.plain, "tool": tool.id,
                "tool_plain": tool.plain, "tool_diameter_mm": tool.diameter_mm, "rpm": feeds.rpm,
                "feed_mm_min": feeds.feed_mm_min, "plunge_mm_min": feeds.plunge_mm_min,
                "faces": [info.ref for info in faces], **({"clamped": list(feeds.clamped)}
                                                                       if feeds.clamped else {}),
                **({"name": op.params["name"]} if op.params.get("name") else {})}
            if any(f["severity"] == "error" for f in found):
                continue        # not handed to FreeCAD: what it would plan there is what the finding says is wrong
            planned.append(op)
            targets[op.index] = _targets(op, faces, holes, final_z, frame, mesh, part.face_of_triangle, tool)
            if op.op == "drill":
                # FreeCAD drills the holes whose walls it is given: whichever face of a hole the job names, its wall.
                ordinals = [ordinal_of[ref] for ref in dict.fromkeys(holes[info.ref]["faces"][0] for info in faces)]
            else:
                ordinals = [info.ordinal for info in faces]
            specs.append({"index": op.index, "op": op.op, "tool": op.tool, "faces": ordinals,
                          "coolant": op.params["coolant"], "leave_mm": op.params.get("leave_mm", 0.0),
                          "stepover": stepover or 0.4, "final_z": final_z,
                          "stepdown_mm": op.params.get("stepdown_mm") or default_stepdown(parsed.material, tool),
                          "side": op.params.get("side"), "peck_mm": op.params.get("peck_mm"),
                          "feeds": {"rpm": feeds.rpm, "feed_mm_min": feeds.feed_mm_min,
                                    "plunge_mm_min": feeds.plunge_mm_min}})
        files = _files(document.stem, setup.id, planned, post)
        moves = None
        if planned:
            plan = {"stock": {"min": s_low.tolist(), "max": s_high.tolist()}, "retract_mm": setup.retract_mm,
                    "clearance_mm": setup.clearance_mm, "tolerance_mm": parsed.tolerance_mm,
                    "tools": [dict(tools[t].as_dict()) for t in dict.fromkeys(op.tool for op in planned)],
                    "operations": specs, "post": post["freecad"], "post_args": post["args"],
                    "work_offset": machine.work_offset, "files": files}
            with logger.timed(f"FreeCAD plans setup {setup.id}"):
                try:
                    report, texts = runner.run(freecad, plan, lambda path: frame.write_brep(part.shape, path))
                except RuntimeError as exc:
                    raise CamJobError(f"setup {setup.id}: {exc}") from None
            commands = {entry["index"]: entry["commands"] for entry in report["operations"]}
            start = (0.0, 0.0, stock_top + setup.clearance_mm)
            moves = toolpath.read([(op.index, commands[op.index]) for op in planned], start, machine.rapid_mm_min)
            with logger.timed(f"check setup {setup.id}"):
                findings += checks.held(setup.id, planned, specs, report["operations"])
                findings += checks.check_moves(setup.id, moves, planned, tools, mesh, s_low, s_high, machine, targets)
                spec_of = {spec["index"]: spec for spec in specs}
                for name, indices in files:
                    findings += checks.posted(setup.id, name, texts[name], [spec_of[i] for i in indices],
                                             machine.work_offset)
            header = (_comment(f"cadgen cam: {parsed.name}, from {document.name}, setup {setup.id}, planned and posted by "
                               f"{freecad.label} for {machine.post}") + "\n" + _comment(_SAFETY) + "\n")
            posted += [(setup.id, name, header + texts[name], tool)
                       for (name, _), tool in zip(files, _file_tools(files, planned))]
            lines += line_segments(moves, setup=setup.id, t_offset=clock, to_part=frame.to_part)
        setup_time = float(moves.t[-1]) if moves is not None else 0.0
        ops_out = []
        for op in setup.operations:
            row = rows[op.index]
            mine = np.nonzero(moves.op == op.index)[0] if moves is not None else np.array([], dtype=int)
            t0 = clock + (float(moves.t[mine[0] - 1]) if len(mine) and mine[0] > 0 else 0.0)
            t1 = clock + (float(moves.t[mine[-1]]) if len(mine) else 0.0)
            row.update({"time_s": round(max(0.0, t1 - t0), 2), "t0": round(t0, 3), "t1": round(max(t0, t1), 3)})
            faces_words = f" {', '.join(row['faces'])}" if row["faces"] else ""
            floors = floors_of.get(op.index)
            if floors:
                faces_words += " (" + "; ".join(f"for pocket floor {floor}: its walls {', '.join(walls)}"
                                                for floor, walls in floors.items()) + ")"
            row["summary"] = f"{op.plain}{faces_words} with {row['tool']} {row['tool_plain']}, " \
                             f"{_duration_words(row['time_s'])}"
            ops_out.append(row)
        operations_out += ops_out
        setups_out.append({"id": setup.id, "plain": setup.id, "orientation": setup.orientation,
                           "origin": setup.origin, "origin_part_mm": [round(float(v), 4) for v in
                                                                    frame.to_part([[0.0, 0.0, 0.0]])[0]],
                           "matrix": frame.matrix(), "time_s": round(setup_time, 2), "t0": round(clock, 3),
                           "t1": round(clock + setup_time, 3), "operations": ops_out})
        clock += setup_time

    # One warning a tool, however many of its operations the machine's limit holds.
    findings += [finding("limits", "warning", "clamped", f"{tool_id} {tools[tool_id].plain}: {words}",
                         "the machine's limit holds the table's number", items)
                 for (tool_id, words), items in clamps.items()]
    findings = by_severity(findings)
    errors = sum(f["severity"] == "error" for f in findings)
    warning_count = sum(f["severity"] == "warning" for f in findings)
    used = list(dict.fromkeys(op.tool for setup in parsed.setups for op in setup.operations))
    verdict = {"status": "ready" if not errors else "fix", "headline": headline(errors, clock, len(used)),
               "errors": errors, "warnings": warning_count, "duration_s": round(clock, 2), "tools": len(used)}
    warnings = []
    if errors:
        verdict["gcode"] = f"G-code not written: fix {errors} error{'s' if errors != 1 else ''} first"
        warnings.append(verdict["gcode"])
        posted = []
    folder = glb_path.parent
    posts_out = [{"setup": setup_id, "file": name, "post": machine.post, "tool": tool}
                 for setup_id, name, _, tool in posted]
    cam = {
        "schema": 1, "generator": "cadgen cam", "planner": freecad.label, "document": _relative(document, folder),
        "occurrence": part.occurrence, "units": "mm", "verdict": verdict,
        "machine": {"post": machine.post, "name": machine.name},
        "material": parsed.material.name, "material_plain": parsed.material.plain,
        "stock": {"min_mm": [round(float(v), 4) for v in stock_low], "max_mm": [round(float(v), 4) for v in stock_high]},
        "tools": [tools[t].as_dict() for t in sorted(tools, key=lambda t: tools[t].number)],
        "setups": setups_out, "findings": findings, "posts": posts_out, "duration_s": round(clock, 3),
        "warnings": warnings, "assumed": [dict(entry) for entry in parsed.assumed], "safety": _SAFETY,
    }
    stock_mesh = _box_mesh(stock_low, stock_high)
    stale = [path for path in _previous_posts(glb_path, document.stem) if path.name not in {p[1] for p in posted}]
    written = _write(glb_path, lambda path: write_glb(path, part_mesh=(part.vertices, part.triangles),
                                                     stock_mesh=stock_mesh, lines=lines, cam=cam,
                                                     name=f"{document.stem} cam"),
                     [(folder / name, text) for _, name, text, _ in posted])
    for path in stale:
        path.unlink(missing_ok=True)
    timings["total_s"] = round(time.perf_counter() - started, 4)
    changes = _tool_changes(parsed)
    summary = {"duration_s": round(clock, 2), "tools": used, "tool_changes": changes, "setups": len(parsed.setups),
               "operations": len(operations_out), "post": machine.post,
               "material": parsed.material.name, "planner": freecad.label}
    return CamPlanResult(ok=True, document=document, glb=glb_path,
                         posts=tuple(dict(p, file=str(path)) for p, path in zip(posts_out, written)),
                         verdict=verdict, summary=summary, operations=tuple(operations_out), findings=tuple(findings),
                         warnings=tuple(warnings), timings=timings, assumed=tuple(dict(e) for e in parsed.assumed))


def _comment(text: str) -> str:
    """``text`` as one G-code comment line: in parentheses, which no controller nests (Fanuc's, LinuxCNC's and GRBL's
    comments end at the first ``)``), so each parenthesis in it is a bracket (``part [1].step``); and anything but
    printable ASCII, or a ``%`` (on Fanuc the end of the program's tape), is a ``?``."""
    text = text.replace("(", "[").replace(")", "]")
    return "(" + "".join(ch if " " <= ch <= "~" and ch != "%" else "?" for ch in text) + ")"


def _files(stem: str, setup_id: str, planned, post) -> list[tuple[str, list[int]]]:
    """The posted files of a setup: one, or (a controller that cannot change tools) one per run of one tool, each
    ``(name, operation indices)``."""
    if not planned:
        return []
    if post["tool_change"]:
        return [(f"{stem}.{setup_id}{post['ext']}", [op.index for op in planned])]
    groups: list[tuple[str, list[int]]] = []
    for op in planned:
        if groups and groups[-1][0] == op.tool:
            groups[-1][1].append(op.index)
        else:
            groups.append((op.tool, [op.index]))
    names = [f"{stem}.{setup_id}.{k + 1}-{tool}{post['ext']}" if len(groups) > 1 else f"{stem}.{setup_id}{post['ext']}"
             for k, (tool, _) in enumerate(groups)]
    return [(name, indices) for name, (_, indices) in zip(names, groups)]


def _file_tools(files, planned) -> list[str | None]:
    """Each posted file's one tool when its setup is split by tool, else None."""
    if len(files) < 2:
        return [None] * len(files)
    tool_of = {op.index: op.tool for op in planned}
    return [tool_of[indices[0]] for _, indices in files]


def _tool_changes(parsed) -> dict:
    """``{"count", "order"}``: how often the running order switches tool, across setups too."""
    order: list[str] = []
    for setup in parsed.setups:
        for op in setup.operations:
            if not order or order[-1] != op.tool:
                order.append(op.tool)
    return {"count": max(0, len(order) - 1), "order": order}


def _box_mesh(low, high):
    import numpy as np

    corners = np.array([[x, y, z] for x in (low[0], high[0]) for y in (low[1], high[1]) for z in (low[2], high[2])])
    quads = [(0, 1, 3, 2), (4, 6, 7, 5), (0, 4, 5, 1), (2, 3, 7, 6), (0, 2, 6, 4), (1, 5, 7, 3)]
    triangles = [t for a, b, c, d in quads for t in ((a, b, c), (a, c, d))]
    return corners, np.array(triangles, dtype=np.int64)


def _write(glb_path: Path, write_glb_to, files: list[tuple[Path, str]]) -> list[Path]:
    """The GLB and ``files`` to temporary names beside them, then each renamed into place. Each earlier file is kept
    under another name (a hard link, else a copy) until every rename is done, so a failure anywhere puts every earlier
    file back byte for byte and leaves none this run wrote."""
    suffix = temp_suffix()
    targets = [glb_path, *(path for path, _ in files)]
    temporaries = [path.with_name(f".{path.name}{suffix}") for path in targets]
    kept = {path: path.with_name(f".{path.name}{suffix}.old") for path in targets if path.exists()}
    placed: list[Path] = []
    try:
        glb_path.parent.mkdir(parents=True, exist_ok=True)
        write_glb_to(temporaries[0])
        for tmp, (_, text) in zip(temporaries[1:], files):
            tmp.write_text(text, encoding="utf-8", newline="\n")
        for path, old in kept.items():
            try:
                os.link(path, old)
            except OSError:
                shutil.copy2(path, old)
        for tmp, final in zip(temporaries, targets):
            replace_atomic(tmp, final)
            placed.append(final)
    except BaseException:
        for final in placed:
            if final in kept:
                replace_atomic(kept[final], final)
            else:
                final.unlink(missing_ok=True)
        raise
    finally:
        for path in (*temporaries, *kept.values()):
            path.unlink(missing_ok=True)
    return [path for path, _ in files]
