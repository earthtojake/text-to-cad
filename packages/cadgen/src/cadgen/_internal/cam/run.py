__all__ = ["headline", "list_features", "plan_job"]

_SAFETY = ("Generated by cadgen with FreeCAD; not proven on a machine. Air-cut or single-block it first, and check the "
           "work offset and every tool length.")


def job_finding(message: str, kind: str = "job") -> dict:
    """A job that cannot run, as the one error finding its result carries."""
    what = ("install FreeCAD as the summary says and plan again" if kind == "freecad"
            else "change the job (or the --occurrence) as the summary says and plan again")
    return finding("job", "error", kind, message, f"the job was refused before anything was planned; nothing was "
                   f"written: {what}")


def _internal(exc: Exception, what: str) -> dict:
    return finding("job", "error", "internal_error", f"cadgen cam failed {what} ({type(exc).__name__}: "
                   f"{str(exc)[:200]})", "this is a bug in cadgen, not in the part: report it with the part")


def list_features(target: Path, *, occurrence: str | None = None) -> CamFeaturesResult:
    from cadgen._internal.cam.features import read_features
    from cadgen._internal.cam.part import read_part

    document = Path(target)
    try:
        part = read_part(document, occurrence=occurrence)
        reading = read_features(part)
    except CamJobError as exc:
        return CamFeaturesResult(ok=False, document=document, findings=(job_finding(str(exc)),))
    except OSError as exc:
        return CamFeaturesResult(ok=False, document=document, findings=(job_finding(
            f"{document.name} could not be read: {exc.strerror or exc}"),))
    except Exception as exc:  # noqa: BLE001 - a bug in cadgen is a refusal that says so, never a traceback
        return CamFeaturesResult(ok=False, document=document, findings=(_internal(exc, "reading this part"),))
    low, high = part.bbox
    bbox = {"min": [round(float(v), 4) + 0.0 for v in low], "max": [round(float(v), 4) + 0.0 for v in high],
            "size": [round(float(b - a), 4) + 0.0 for a, b in zip(low, high)]}
    return CamFeaturesResult(ok=True, document=document, occurrence=part.occurrence, bbox_mm=bbox,
                             faces=tuple(reading["faces"]), holes=tuple(reading["holes"]),
                             floors=tuple(reading["floors"]))


